/**
 * What the demo looks like for each trade.
 *
 * A wholesaler's shelf tells a pharmacist nothing, and the first thing anyone
 * does with a demo is look for their own stock on it. So the demo asks which
 * business you run and seeds that one: the right shelf, the right sections,
 * the right wording, and for a clinic a waiting room with people in it.
 *
 * Only the identity and the shelf live here. Everything built on top — sales,
 * stock movements, debts, shifts — is generated from whatever products this
 * hands back, so a new trade is a list of goods and nothing else.
 */

import type { IndustryId } from "@/lib/industry";

/** A product as the seed wants it, before ids and dates are stamped on. */
export type SeedProduct = {
  name: string;
  category: string;
  buy: number;
  sell: number;
  wholesale: number;
  stock: number;
  reorder: number;
  extra?: Record<string, unknown>;
};

export type DemoTrade = {
  id: IndustryId;
  /** What the picker calls it. */
  label: string;
  blurb: string;
  business: { name: string; tagline: string; address: string; city: string };
  products: SeedProduct[];
};

/** Days from today, as the seed's own date helper expects. */
const inDays = (days: number) => {
  const d = new Date();
  d.setDate(d.getDate() + days);
  return d.toISOString().slice(0, 10);
};

